#!/usr/bin/env bash
set -uo pipefail
cd "$(dirname "$0")/.." || exit 2
mkdir -p Docs/Validation
run_dir="$(mktemp -d "$PWD/Docs/Validation/playback-entitlement-XXXXXX")" || exit 2
simulator_id="${SIMULATOR_ID:-}"
if [ -z "$simulator_id" ]; then
  simulator_id="$(xcrun simctl list devices available -j | python3 -c 'import json,sys; d=json.load(sys.stdin); a=[v for group in d["devices"].values() for v in group if v.get("isAvailable") and "iPhone" in v["name"]]; a.sort(key=lambda v: v.get("state") != "Booted"); print(a[0]["udid"] if a else "")')"
fi
if [ -z "$simulator_id" ]; then
  echo 'NOT TESTED: no available iPhone simulator' | tee -a "$run_dir/RESULTS.txt"
  exit 2
fi
{ git rev-parse HEAD; git status --short; xcodebuild -version; echo "Simulator: $simulator_id"; } > "$run_dir/environment.txt" 2>&1
build_dir="$(mktemp -d /private/tmp/streamlab-playback-entitlement-XXXXXX)" || exit 2
echo "Build directory: $build_dir" >> "$run_dir/environment.txt"
echo 'Simulator signing: CODE_SIGNING_ALLOWED=YES CODE_SIGN_IDENTITY=- (ad hoc)' >> "$run_dir/environment.txt"
echo "Running Mock entitlement rejection and renewal UI regression. Log: $run_dir/ui-tests.log"
# Runtime Keychain tests need the app identity entitlements generated by Xcode.
# Disabling signing is suitable for compile-only checks, not this login test.
xcodebuild -project StreamLab.xcodeproj -scheme StreamLab -configuration Debug \
  -destination "platform=iOS Simulator,id=$simulator_id" \
  -derivedDataPath "$build_dir/DerivedData" -resultBundlePath "$run_dir/UITests.xcresult" \
  -parallel-testing-enabled NO \
  -test-timeouts-enabled YES -default-test-execution-time-allowance 900 -maximum-test-execution-time-allowance 900 \
  -only-testing:StreamLabUITests/StreamLabUITests/testExpiredPlaybackEntitlementBlocksLocalDemoAndRenews \
  -only-testing:StreamLabUITests/StreamLabUITests/testUnavailablePlaybackKeyBlocksAndRecovers \
  -only-testing:StreamLabUITests/StreamLabUITests/testPlaybackEntitlementRenewalFailureIsRecoverable \
  -only-testing:StreamLabUITests/StreamLabUITests/testPlaybackCloseDuringAuthorizationAndReopenForKids \
  SWIFT_TREAT_WARNINGS_AS_ERRORS=YES CODE_SIGNING_ALLOWED=YES CODE_SIGN_IDENTITY=- test > "$run_dir/ui-tests.log" 2>&1
result=$?
app_path="$build_dir/DerivedData/Build/Products/Debug-iphonesimulator/StreamLab.app"
{
  echo "Built app: $app_path"
  codesign --verify --verbose=2 "$app_path"
  echo "Signature verification exit=$?"
  codesign -d --entitlements - "$app_path"
  echo "Entitlement inspection exit=$?"
} > "$run_dir/signing.log" 2>&1
if [ "$result" -eq 0 ]; then
  if ! grep -Eq 'testExpiredPlaybackEntitlementBlocksLocalDemoAndRenews.*passed' "$run_dir/ui-tests.log" ||
     ! grep -Eq 'testUnavailablePlaybackKeyBlocksAndRecovers.*passed' "$run_dir/ui-tests.log" ||
     ! grep -Eq 'testPlaybackEntitlementRenewalFailureIsRecoverable.*passed' "$run_dir/ui-tests.log" ||
     ! grep -Eq 'testPlaybackCloseDuringAuthorizationAndReopenForKids.*passed' "$run_dir/ui-tests.log"; then
    echo 'FAIL required entitlement tests did not all pass' >> "$run_dir/RESULTS.txt"
    result=1
  fi
fi
if [ "$result" -eq 0 ]; then
  echo 'PASS four entitlement/cancellation UI tests' | tee "$run_dir/RESULTS.txt"
else
  echo "FAIL entitlement UI exit=$result" | tee "$run_dir/RESULTS.txt"
fi
echo 'NOT TESTED: real DRM/license server, real HLS, device offline entitlement, full UI suite' >> "$run_dir/RESULTS.txt"
tail -n 35 "$run_dir/ui-tests.log"
echo "Results: $run_dir/RESULTS.txt"
exit "$result"
